#!/usr/bin/env node
// Writes docs/TOOLS.md from the running server's tool list, so the reference
// cannot drift from the code. Run after `npm run build`:
//   node scripts/gen-tool-docs.mjs
// No network: the server only lists tools. A placeholder token keeps it from
// refusing to start; FASTMAIL_MCP_TOKEN is cleared so official_* stay out.
import { Client } from '@modelcontextprotocol/client';
import { StdioClientTransport } from '@modelcontextprotocol/client/stdio';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const env = { ...process.env, FASTMAIL_API_TOKEN: 'placeholder-for-docs' };
delete env.FASTMAIL_MCP_TOKEN;

const transport = new StdioClientTransport({ command: process.execPath, args: [join(root, 'dist/index.js')], env, stderr: 'ignore' });
// auto picks 2026-07-28 when the server offers it, so this run also checks that path.
const client = new Client({ name: 'gen-tool-docs', version: '1.0.0' }, { versionNegotiation: { mode: 'auto' } });
await client.connect(transport);
if (client.getNegotiatedProtocolVersion() !== '2026-07-28') throw new Error(`server did not negotiate 2026-07-28 (got ${client.getNegotiatedProtocolVersion()})`);
const { tools } = await client.listTools();
await client.close();

// Group by the first word of the name, with a few merges so the sections read well.
const GROUP = {
  list: 'Listing and search', search: 'Listing and search', advanced: 'Listing and search', get: 'Read', find: 'Listing and search',
  summarize: 'Listing and search', extract: 'Listing and search',
  bulk: 'Bulk operations', undo: 'Bulk operations', export: 'Bulk operations',
  create: 'Create and update', update: 'Create and update', edit: 'Create and update', merge: 'Create and update',
  delete: 'Delete and trash', empty: 'Delete and trash',
  send: 'Sending', reply: 'Sending', forward: 'Sending', cancel: 'Sending', snooze: 'Sending', unsnooze: 'Sending',
  mark: 'Email state', move: 'Email state', archive: 'Email state', pin: 'Email state', add: 'Email state', remove: 'Email state',
  report: 'Email state', unsubscribe: 'Email state', import: 'Email state',
  download: 'Attachments', save: 'Attachments',
  set: 'Account', validate: 'Account', check: 'Account', test: 'Account',
};
const ORDER = ['Listing and search', 'Read', 'Email state', 'Bulk operations', 'Create and update', 'Delete and trash', 'Sending', 'Attachments', 'Account', 'Other', 'Official passthrough'];
const sections = new Map(ORDER.map((g) => [g, []]));
for (const t of tools.sort((a, b) => a.name.localeCompare(b.name))) {
  const g = t.name.startsWith('official_') ? 'Official passthrough' : GROUP[t.name.split('_')[0]] ?? 'Other';
  sections.get(g).push(t);
}
for (const [g, list] of sections) if (!list.length) sections.delete(g);

const param = ([name, p], required) => {
  const type = Array.isArray(p.type) ? p.type.join(' | ') : p.type ?? (p.oneOf ? 'one of' : 'any');
  const req = required.includes(name) ? ', required' : '';
  const desc = p.description ? ` ${p.description.replace(/\s+/g, ' ')}` : '';
  return `  - \`${name}\` (${type}${req})${desc}`;
};

let out = `# Tool reference\n\nGenerated by \`node scripts/gen-tool-docs.mjs\` from the server's own tool list. ${tools.length} tools. Do not edit by hand; rebuild and rerun the script.\n\n`;
out += 'A fork tool with the same name as an upstream tool replaces it and keeps every upstream argument. `official_*` tools appear only with `FASTMAIL_MCP_TOKEN` set and are not listed here.\n\n*Read-only.* and *Writes.* come from each tool\'s `readOnlyHint` annotation, the same flag `FASTMAIL_READ_ONLY` uses.\n\n';
out += '## Contents\n\n' + [...sections.keys()].map((g) => `- [${g}](#${g.toLowerCase().replace(/[^a-z0-9]+/g, '-')})`).join('\n') + '\n\n';
for (const [g, list] of sections) {
  out += `## ${g}\n\n`;
  for (const t of list) {
    const props = Object.entries(t.inputSchema?.properties ?? {});
    const required = t.inputSchema?.required ?? [];
    const kind = t.annotations?.readOnlyHint ? '*Read-only.*' : '*Writes.*';
    out += `### \`${t.name}\`\n\n${kind} ${(t.description ?? '').trim()}\n\n`;
    out += props.length ? props.map((e) => param(e, required)).join('\n') + '\n\n' : '  No parameters.\n\n';
  }
}
writeFileSync(join(root, 'docs/TOOLS.md'), out);
console.log(`docs/TOOLS.md: ${tools.length} tools in ${sections.size} sections`);
